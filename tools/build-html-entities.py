#!/usr/bin/env python3
"""Builds src/html-entities.ts from the tables of Python's html module.

Usage: python tools/build-html-entities.py [--check] [output.ts]

Without arguments the script writes src/html-entities.ts (next to this tools/ directory). With --check it writes
nothing and exits with 1 when the file on disk differs from what this Python version would generate.

The data is html.entities.html5 (the WHATWG named character references), html._invalid_charrefs (numeric references
that HTML5 maps to another character) and html._invalid_codepoints (code points that html.unescape drops). The
generated file lets src/html-unescape.ts decode exactly like html.unescape of CPython 3.14.
"""
import html
import json
import platform
import sys
from html.entities import html5
from pathlib import Path

DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "src" / "html-entities.ts"
CODE_POINTS_PER_LINE = 12


def literal(text: str) -> str:
    """A TypeScript string literal: JSON with every non-ASCII character as a lower-case \\uXXXX escape."""
    return json.dumps(text, ensure_ascii=True)


def render() -> str:
    lines = [
        f"// Generated from Python {platform.python_version()} "
        "(html.entities.html5, html._invalid_charrefs, html._invalid_codepoints):",
        "// the WHATWG HTML named character references and the HTML5 rules for invalid numeric references.",
        "// Used by html-unescape.ts to decode entities exactly like Python's html.unescape().",
        "// Generated by tools/build-html-entities.py. Do not edit by hand.",
        "",
        "/** Named character references, keys without the leading '&' (with and without ';' where HTML5 allows both). */",
        "export const HTML5_NAMED_REFERENCES: Readonly<Record<string, string>> = {",
    ]
    for name in sorted(html5):
        lines.append(f"  {literal(name)}: {literal(html5[name])},")
    lines += [
        "};",
        "",
        "/** Numeric references that HTML5 maps to another character (windows-1252 block and NUL). */",
        "export const INVALID_NUMERIC_REFERENCES: Readonly<Record<number, string>> = {",
    ]
    for code in sorted(html._invalid_charrefs):
        lines.append(f"  {code}: {literal(html._invalid_charrefs[code])},")
    lines += [
        "};",
        "",
        "/** Code points that HTML5 drops when referenced numerically. */",
        "export const DROPPED_CODE_POINTS: ReadonlySet<number> = new Set([",
    ]
    dropped = [f"0x{code:x}" for code in sorted(html._invalid_codepoints)]
    for start in range(0, len(dropped), CODE_POINTS_PER_LINE):
        lines.append("  " + ", ".join(dropped[start:start + CODE_POINTS_PER_LINE]) + ",")
    lines.append("]);")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv
    paths = [argument for argument in argv if argument != "--check"]
    output = Path(paths[0]) if paths else DEFAULT_OUTPUT
    generated = render()
    if check:
        current = output.read_bytes().decode("utf-8")
        if current == generated:
            print(f"{output} is up to date.")
            return 0
        expected_lines = generated.split("\n")
        current_lines = current.split("\n")
        for number, (want, have) in enumerate(zip(expected_lines, current_lines), start=1):
            if want != have:
                print(f"{output} differs at line {number}:\n  generated: {want}\n  on disk:   {have}")
                break
        else:
            print(f"{output} differs in length: generated {len(expected_lines)} lines, on disk {len(current_lines)}.")
        return 1
    output.write_bytes(generated.encode("utf-8"))
    print(f"Wrote {output} ({len(html5)} named references).")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
